from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT_PATH = REPO_ROOT / "scripts" / "install_llm_wiki.py"
MARKER = "<!-- generated-by: install_llm_wiki -->"


class InstallLlmWikiTests(unittest.TestCase):
    def make_target(self) -> Path:
        temp_dir = Path(tempfile.mkdtemp(prefix="install-llm-wiki-"))
        self.addCleanup(lambda: shutil.rmtree(temp_dir, ignore_errors=True))
        return temp_dir

    def run_install(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT_PATH), *args],
            capture_output=True,
            text=True,
            check=False,
        )

    def test_generates_read_only_and_ingest_skills_pointing_to_wiki_root(self) -> None:
        target = self.make_target()

        result = self.run_install("--target", str(target), "--wiki-root", str(REPO_ROOT))

        self.assertEqual(result.returncode, 0, msg=result.stderr)
        read_only = (target / "llm-wiki" / "SKILL.md").read_text(encoding="utf-8")
        ingest = (target / "llm-wiki-ingest" / "SKILL.md").read_text(encoding="utf-8")
        self.assertIn(MARKER, read_only)
        self.assertIn(MARKER, ingest)
        self.assertIn(str(REPO_ROOT.resolve()), read_only)
        self.assertIn(str(REPO_ROOT.resolve()), ingest)
        self.assertIn("name: llm-wiki\n", read_only)
        self.assertIn("name: llm-wiki-ingest\n", ingest)
        self.assertIn("read-only", read_only.lower())
        self.assertIn(
            str((REPO_ROOT / ".agents" / "skills" / "wiki-ingest" / "SKILL.md").resolve()),
            ingest,
        )

    def test_generated_output_is_deterministic(self) -> None:
        first = self.make_target()
        second = self.make_target()

        self.run_install("--target", str(first), "--wiki-root", str(REPO_ROOT))
        self.run_install("--target", str(second), "--wiki-root", str(REPO_ROOT))

        for name in ("llm-wiki", "llm-wiki-ingest"):
            self.assertEqual(
                (first / name / "SKILL.md").read_bytes(),
                (second / name / "SKILL.md").read_bytes(),
            )

    def test_dry_run_writes_nothing(self) -> None:
        target = self.make_target()

        result = self.run_install("--target", str(target), "--wiki-root", str(REPO_ROOT), "--dry-run")

        self.assertEqual(result.returncode, 0, msg=result.stderr)
        self.assertIn("llm-wiki", result.stdout)
        self.assertEqual(list(target.iterdir()), [])

    def test_refuses_wiki_root_without_index(self) -> None:
        target = self.make_target()
        bogus_root = self.make_target()

        result = self.run_install("--target", str(target), "--wiki-root", str(bogus_root))

        self.assertNotEqual(result.returncode, 0)
        self.assertIn("wiki/index.md", result.stderr)
        self.assertEqual(list(target.iterdir()), [])

    def test_refuses_to_overwrite_foreign_skill_directory(self) -> None:
        target = self.make_target()
        foreign = target / "llm-wiki"
        foreign.mkdir()
        (foreign / "SKILL.md").write_text("---\nname: llm-wiki\n---\nhand written\n", encoding="utf-8")

        result = self.run_install("--target", str(target), "--wiki-root", str(REPO_ROOT))

        self.assertNotEqual(result.returncode, 0)
        self.assertIn("not generated by install_llm_wiki", result.stderr)
        self.assertEqual(
            (foreign / "SKILL.md").read_text(encoding="utf-8"),
            "---\nname: llm-wiki\n---\nhand written\n",
        )

    def test_reinstall_over_generated_skill_is_allowed(self) -> None:
        target = self.make_target()
        self.assertEqual(
            self.run_install("--target", str(target), "--wiki-root", str(REPO_ROOT)).returncode,
            0,
        )

        result = self.run_install("--target", str(target), "--wiki-root", str(REPO_ROOT))

        self.assertEqual(result.returncode, 0, msg=result.stderr)


if __name__ == "__main__":
    unittest.main()
