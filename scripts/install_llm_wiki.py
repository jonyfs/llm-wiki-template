#!/usr/bin/env python3
from __future__ import annotations

import argparse
import sys
from pathlib import Path


MARKER = "<!-- generated-by: install_llm_wiki -->"
DEFAULT_TARGET = Path.home() / ".config" / "opencode" / "skills"
REPO_ROOT = Path(__file__).resolve().parents[1]

READ_ONLY_TEMPLATE = """---
name: llm-wiki
description: Read-only access to the shared LLM wiki at {wiki_root}. Use to answer questions from that wiki. Never writes, creates, updates, or deletes any file.
---

{marker}

# LLM Wiki (read-only)

This skill reads a shared LLM wiki maintained in another repository. Its root is:

`{wiki_root}`

## Rules

- Read-only. Do not write, create, update, rename, or delete any file under that root.
- Follow the full playbook in `{wiki_skill}`, but ignore every write step in it.
- Start from `{wiki_root}/wiki/index.md`, then read the relevant pages.
- Use `{wiki_root}/raw/` only to verify a claim that the wiki does not settle.
- For search, run `python3 {wiki_root}/scripts/wiki_search.py "<terms>"` when that script exists.
- To add material to the wiki, use the `llm-wiki-ingest` skill instead.
"""

INGEST_TEMPLATE = """---
name: llm-wiki-ingest
description: Ingest material into the shared LLM wiki at {wiki_root} by delegating to its wiki-ingest playbook. Writes only to that repository.
---

{marker}

# LLM Wiki Ingest (remote)

This skill ingests content into a shared LLM wiki maintained in another repository. Its root is:

`{wiki_root}`

## Rules

- Follow the playbook in `{ingest_skill}` exactly. It is the authority for ingest.
- All writes go to `{wiki_root}`, never to the current project.
- Source material must be placed in `{wiki_root}/raw/` only when the user explicitly asks for it. Never modify existing `raw/` files.
- Log every change in `{wiki_root}/wiki/log.md` and update `{wiki_root}/wiki/index.md`.
- Run `python3 -m unittest discover -s tests -t .` from `{wiki_root}` after ingest.
"""


def fail(message: str) -> int:
    print(f"install-llm-wiki failed: {message}", file=sys.stderr)
    return 2


def is_generated(skill_file: Path) -> bool:
    if not skill_file.is_file():
        return False
    return MARKER in skill_file.read_text(encoding="utf-8")


def render(wiki_root: Path) -> dict[str, str]:
    wiki_skill = wiki_root / ".agents" / "skills" / "wiki" / "SKILL.md"
    ingest_skill = wiki_root / ".agents" / "skills" / "wiki-ingest" / "SKILL.md"
    context = {
        "wiki_root": wiki_root.as_posix(),
        "wiki_skill": wiki_skill.as_posix(),
        "ingest_skill": ingest_skill.as_posix(),
        "marker": MARKER,
    }
    return {
        "llm-wiki": READ_ONLY_TEMPLATE.format(**context),
        "llm-wiki-ingest": INGEST_TEMPLATE.format(**context),
    }


def plan(target: Path, wiki_root: Path) -> tuple[dict[str, str], str | None]:
    for name in ("llm-wiki", "llm-wiki-ingest"):
        skill_file = target / name / "SKILL.md"
        if skill_file.exists() and not is_generated(skill_file):
            return {}, f"{skill_file} exists and was not generated by install_llm_wiki"
    return render(wiki_root), None


def run(target: Path, wiki_root: Path, dry_run: bool) -> int:
    if not (wiki_root / "wiki" / "index.md").is_file():
        return fail(f"{wiki_root} has no wiki/index.md; not a wiki root")
    if not (wiki_root / ".agents" / "skills" / "wiki-ingest" / "SKILL.md").is_file():
        return fail(f"{wiki_root} has no .agents/skills/wiki-ingest/SKILL.md")

    files, error = plan(target, wiki_root)
    if error is not None:
        return fail(error)

    for name, text in files.items():
        skill_file = target / name / "SKILL.md"
        if dry_run:
            print(f"would write {skill_file}")
            continue
        skill_file.parent.mkdir(parents=True, exist_ok=True)
        skill_file.write_text(text, encoding="utf-8")
        print(f"wrote {skill_file}")
    return 0


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Install read-only llm-wiki and remote llm-wiki-ingest skills that point to a shared wiki."
    )
    parser.add_argument("--target", default=str(DEFAULT_TARGET), help="Skills directory to install into.")
    parser.add_argument("--wiki-root", default=str(REPO_ROOT), help="Root of the shared LLM wiki repository.")
    parser.add_argument("--dry-run", action="store_true", help="Print planned writes without writing.")
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    return run(Path(args.target).expanduser().resolve(), Path(args.wiki_root).expanduser().resolve(), args.dry_run)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
